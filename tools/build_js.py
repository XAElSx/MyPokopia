"""Wrap the JSON database in a .js file the site loads with a <script> tag.

Usage: python tools/build_js.py <db.json> <out.js>

Why: browsers block fetch() of local .json files when index.html is opened
straight from the folder. A script tag works both from the folder and on GitHub Pages.
The .json stays the source of truth; never edit the .js by hand.
"""
import json, sys


def main(db_path, out_path):
    db = json.load(open(db_path, encoding="utf-8"))
    body = json.dumps(db, ensure_ascii=False, separators=(",", ":"))
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// GENERATED by tools/build_js.py from pokopia-pokemon.json. Do not edit.\n")
        f.write("window.POKOPIA_DB = " + body + ";\n")
    print(f"wrote {out_path} ({db['count']} Pokémon)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
