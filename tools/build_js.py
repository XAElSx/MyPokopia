"""Wrap a JSON database in a .js file the site loads with a <script> tag.

Usage: python tools/build_js.py <db.json> <out.js> [GLOBAL_NAME]     (default global: POKOPIA_DB)

Why: browsers block fetch() of local .json files when index.html is opened
straight from the folder. A script tag works both from the folder and on GitHub Pages.
The .json stays the source of truth; never edit the .js by hand.
Each data type gets its own global (POKOPIA_DB, POKOPIA_HABITATS, POKOPIA_RECIPES) so pages can load several.
"""
import json, os, sys


def main(db_path, out_path, global_name="POKOPIA_DB"):
    db = json.load(open(db_path, encoding="utf-8"))
    body = json.dumps(db, ensure_ascii=False, separators=(",", ":"))
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(f"// GENERATED by tools/build_js.py from {os.path.basename(db_path)}. Do not edit.\n")
        f.write(f"window.{global_name} = " + body + ";\n")
    print(f"wrote {out_path} ({db['count']} entries, window.{global_name})")


if __name__ == "__main__":
    main(*sys.argv[1:4])
